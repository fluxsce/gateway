CREATE TABLE HUB_GW_CIRCUIT_BREAKER_CONFIG (
  tenantId NVARCHAR(32) NOT NULL,
  circuitBreakerConfigId NVARCHAR(32) NOT NULL,
  routeConfigId NVARCHAR(32) DEFAULT NULL,
  targetServiceId NVARCHAR(32) DEFAULT NULL,
  breakerName NVARCHAR(100) NOT NULL,
  
  -- 根据CircuitBreakerConfig结构设计基础配置
  keyStrategy NVARCHAR(50) NOT NULL DEFAULT N'node',
  
  -- 阈值配置
