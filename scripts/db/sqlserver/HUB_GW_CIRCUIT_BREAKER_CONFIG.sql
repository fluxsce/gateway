  halfOpenMaxRequests INT NOT NULL DEFAULT 3,
  slowCallThreshold INT NOT NULL DEFAULT 60000,
  slowCallRatePercent INT NOT NULL DEFAULT 50,
  
  -- 时间配置
  openTimeoutSeconds INT NOT NULL DEFAULT 60,
  windowSizeSeconds INT NOT NULL DEFAULT 60,
  
  -- 错误处理配置
  errorStatusCode INT NOT NULL DEFAULT 503,
  errorMessage NVARCHAR(500) DEFAULT N'Service temporarily unavailable due to circuit breaker',
  
  -- 存储配置
  storageType NVARCHAR(50) NOT NULL DEFAULT N'memory',
  storageConfig NVARCHAR(MAX) DEFAULT NULL,
  
  configPriority INT NOT NULL DEFAULT 0,
  reserved1 NVARCHAR(100) DEFAULT NULL,
  reserved2 NVARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 DATETIME2 DEFAULT NULL,
  extProperty NVARCHAR(MAX) DEFAULT NULL,
  addTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  addWho NVARCHAR(32) NOT NULL,
  editTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  editWho NVARCHAR(32) NOT NULL,
  oprSeqFlag NVARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag NVARCHAR(1) NOT NULL DEFAULT N'Y',
  noteText NVARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, circuitBreakerConfigId),
  INDEX IDX_GW_CB_ROUTE (routeConfigId),
  INDEX IDX_GW_CB_SERVICE (targetServiceId),
  INDEX IDX_GW_CB_STRATEGY (keyStrategy),
  INDEX IDX_GW_CB_STORAGE (storageType),
  INDEX IDX_GW_CB_PRIORITY (configPriority)
);
