-- SQL Server 方言，由 scripts/db/mysql/HUB_GW_ROUTE_CONFIG.sql 转换。程序初始化会执行本目录除 init.sql 外的全部 .sql。
IF OBJECT_ID(N'dbo.HUB_GW_ROUTE_CONFIG', N'U') IS NULL
CREATE TABLE HUB_GW_ROUTE_CONFIG (
  tenantId NVARCHAR(32) NOT NULL,
  routeConfigId NVARCHAR(32) NOT NULL,
  gatewayInstanceId NVARCHAR(32) NOT NULL,
  routeName NVARCHAR(100) NOT NULL,
  routePath NVARCHAR(200) NOT NULL,
  allowedMethods NVARCHAR(200) DEFAULT NULL,
  allowedHosts NVARCHAR(500) DEFAULT NULL,
  matchType INT NOT NULL DEFAULT 1,
  routePriority INT NOT NULL DEFAULT 100,
  stripPathPrefix NVARCHAR(1) NOT NULL DEFAULT N'N',
  rewritePath NVARCHAR(200) DEFAULT NULL,
  enableWebsocket NVARCHAR(1) NOT NULL DEFAULT N'N',
  timeoutMs INT NOT NULL DEFAULT 30000,
  retryCount INT NOT NULL DEFAULT 0,
  retryIntervalMs INT NOT NULL DEFAULT 1000,
  
  -- 服务关联字段，直接关联服务定义表
  serviceDefinitionId VARCHAR(32) DEFAULT NULL,
  
  -- 日志配置关联字段
  logConfigId NVARCHAR(32) DEFAULT NULL,
  
  -- 路由元数据，用于存储额外配置信息
  routeMetadata NVARCHAR(MAX) DEFAULT NULL,
  
  -- 注意：使用activeFlag代替enabled字段，保持数据库设计一致性
  -- activeFlag='Y'表示路由启用，activeFlag='N'表示路由禁用
  -- 在代码中将activeFlag映射为enabled字段
  
  reserved1 NVARCHAR(100) DEFAULT NULL,
  reserved2 NVARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 DATETIME2 DEFAULT NULL,
  extProperty NVARCHAR(MAX) DEFAULT NULL,
  addTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  addWho NVARCHAR(32) NOT NULL,
  editTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  editWho NVARCHAR(32) NOT NULL,
  oprSeqFlag NVARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag NVARCHAR(1) NOT NULL DEFAULT N'Y',
  noteText NVARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, routeConfigId),
  INDEX IDX_GW_ROUTE_INST (gatewayInstanceId),
  INDEX IDX_GW_ROUTE_SERVICE (serviceDefinitionId),
  INDEX IDX_GW_ROUTE_LOG (logConfigId),
  INDEX IDX_GW_ROUTE_PRIORITY (routePriority),
  INDEX IDX_GW_ROUTE_PATH (routePath),
  INDEX IDX_GW_ROUTE_ACTIVE (activeFlag)
);
