-- 兼容已存在的数据库，修改字段长度
-- 注意：由于字段长度增加到 VARCHAR(1000)，需要先删除索引，修改字段后再重建前缀索引
IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE name = N'IDX_GW_ROUTE_SERVICE' AND parent_object_id = OBJECT_ID(N'dbo.HUB_GW_ROUTE_CONFIG'))
ALTER TABLE HUB_GW_ROUTE_CONFIG DROP CONSTRAINT IDX_GW_ROUTE_SERVICE;
IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IDX_GW_ROUTE_SERVICE' AND object_id = OBJECT_ID(N'dbo.HUB_GW_ROUTE_CONFIG') AND is_primary_key = 0 AND is_unique_constraint = 0)
DROP INDEX IDX_GW_ROUTE_SERVICE ON HUB_GW_ROUTE_CONFIG;
ALTER TABLE HUB_GW_ROUTE_CONFIG ALTER COLUMN serviceDefinitionId VARCHAR(1000) NULL;
-- 重建索引，使用前缀索引（前255个字符，255*4=1020字节，在3072字节限制内）
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IDX_GW_ROUTE_SERVICE' AND object_id = OBJECT_ID(N'dbo.HUB_GW_ROUTE_CONFIG'))
CREATE INDEX IDX_GW_ROUTE_SERVICE ON HUB_GW_ROUTE_CONFIG (serviceDefinitionId);

