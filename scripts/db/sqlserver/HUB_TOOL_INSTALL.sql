-- SQL Server 方言。程序初始化会执行本目录除 init.sql 外的全部 .sql。
IF OBJECT_ID(N'dbo.HUB_TOOL_INSTALL', N'U') IS NULL
CREATE TABLE HUB_TOOL_INSTALL (
  tenantId NVARCHAR(32) NOT NULL,
  userId NVARCHAR(64) NOT NULL,
  toolId NVARCHAR(64) NOT NULL,
  configJson NVARCHAR(MAX) NOT NULL,
  installTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  addTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  addWho NVARCHAR(64) NOT NULL,
  editTime DATETIME2 NOT NULL DEFAULT GETDATE(),
  editWho NVARCHAR(64) NOT NULL,
  oprSeqFlag NVARCHAR(64) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag NVARCHAR(1) NOT NULL DEFAULT N'Y',
  PRIMARY KEY (tenantId, userId, toolId)
);
