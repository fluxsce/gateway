CREATE TABLE IF NOT EXISTS `HUB_TOOL_INSTALL` (
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID',
  `userId` VARCHAR(64) NOT NULL COMMENT '用户ID',
  `toolId` VARCHAR(64) NOT NULL COMMENT '工具ID',
  `configJson` TEXT NOT NULL COMMENT '个人配置JSON',
  `installTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '最近安装时间',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(64) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(64) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(64) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N未安装,Y已安装)',
  PRIMARY KEY (`tenantId`, `userId`, `toolId`)
) ENGINE=InnoDB COMMENT='工具市场安装表 - 按用户保存已安装工具及配置';
