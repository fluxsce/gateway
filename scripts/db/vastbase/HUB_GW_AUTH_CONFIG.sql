-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_AUTH_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  authConfigId VARCHAR(32) NOT NULL,
  gatewayInstanceId VARCHAR(32) DEFAULT NULL,
  routeConfigId VARCHAR(32) DEFAULT NULL,
  authName VARCHAR(100) NOT NULL,
  authType VARCHAR(50) NOT NULL,
  authStrategy VARCHAR(50) DEFAULT 'REQUIRED',
  authConfig TEXT NOT NULL,
  exemptPaths TEXT DEFAULT NULL,
  exemptHeaders TEXT DEFAULT NULL,
  failureStatusCode INT NOT NULL DEFAULT 401,
  failureMessage VARCHAR(200) DEFAULT '认证失败',
  configPriority INT NOT NULL DEFAULT 0,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, authConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_AUTH_INST ON HUB_GW_AUTH_CONFIG (gatewayInstanceId);
CREATE INDEX IF NOT EXISTS IDX_GW_AUTH_ROUTE ON HUB_GW_AUTH_CONFIG (routeConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_AUTH_TYPE ON HUB_GW_AUTH_CONFIG (authType);
CREATE INDEX IF NOT EXISTS IDX_GW_AUTH_PRIORITY ON HUB_GW_AUTH_CONFIG (configPriority);
