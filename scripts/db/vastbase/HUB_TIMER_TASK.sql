-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TIMER_TASK (
  taskId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  taskName VARCHAR(200) NOT NULL,
  taskDescription VARCHAR(500) DEFAULT NULL,
  taskPriority INT NOT NULL DEFAULT 1,
  schedulerId VARCHAR(32) DEFAULT NULL,
  schedulerName VARCHAR(100) DEFAULT NULL,
  scheduleType INT NOT NULL,
  cronExpression VARCHAR(100) DEFAULT NULL,
  intervalSeconds BIGINT DEFAULT NULL,
  delaySeconds BIGINT DEFAULT NULL,
  startTime TIMESTAMP DEFAULT NULL,
  endTime TIMESTAMP DEFAULT NULL,
  maxRetries INT NOT NULL DEFAULT 0,
  retryIntervalSeconds BIGINT NOT NULL DEFAULT 60,
  timeoutSeconds BIGINT NOT NULL DEFAULT 1800,
  taskParams TEXT DEFAULT NULL,
  executorType VARCHAR(50) DEFAULT NULL,
  toolConfigId VARCHAR(32) DEFAULT NULL,
  toolConfigName VARCHAR(100) DEFAULT NULL,
  operationType VARCHAR(100) DEFAULT NULL,
  operationConfig TEXT DEFAULT NULL,
  taskStatus INT NOT NULL DEFAULT 1,
  nextRunTime TIMESTAMP DEFAULT NULL,
  lastRunTime TIMESTAMP DEFAULT NULL,
  runCount BIGINT NOT NULL DEFAULT 0,
  successCount BIGINT NOT NULL DEFAULT 0,
  failureCount BIGINT NOT NULL DEFAULT 0,
  lastExecutionId VARCHAR(32) DEFAULT NULL,
  lastExecutionStartTime TIMESTAMP DEFAULT NULL,
  lastExecutionEndTime TIMESTAMP DEFAULT NULL,
  lastExecutionDurationMs BIGINT DEFAULT NULL,
  lastExecutionStatus INT DEFAULT NULL,
  lastResultSuccess VARCHAR(1) DEFAULT NULL,
  lastErrorMessage TEXT DEFAULT NULL,
  lastRetryCount INT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, taskId)
);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_NAME ON HUB_TIMER_TASK (taskName);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_SCHED ON HUB_TIMER_TASK (schedulerId);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_TYPE ON HUB_TIMER_TASK (scheduleType);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_STATUS ON HUB_TIMER_TASK (taskStatus);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_NEXT ON HUB_TIMER_TASK (nextRunTime);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_LAST ON HUB_TIMER_TASK (lastRunTime);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_ACTIVE ON HUB_TIMER_TASK (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_EXEC ON HUB_TIMER_TASK (executorType);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_TOOL ON HUB_TIMER_TASK (toolConfigId);
CREATE INDEX IF NOT EXISTS IDX_TIMER_TASK_OP ON HUB_TIMER_TASK (operationType);
