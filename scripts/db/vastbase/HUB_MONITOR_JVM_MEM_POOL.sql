-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_MEM_POOL (
  memoryPoolId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  poolName VARCHAR(100) NOT NULL,
  poolType VARCHAR(20) NOT NULL,
  poolCategory VARCHAR(50) DEFAULT NULL,
  currentInitBytes BIGINT NOT NULL DEFAULT 0,
  currentUsedBytes BIGINT NOT NULL DEFAULT 0,
  currentCommittedBytes BIGINT NOT NULL DEFAULT 0,
  currentMaxBytes BIGINT NOT NULL DEFAULT -1,
  currentUsagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  peakInitBytes BIGINT DEFAULT 0,
  peakUsedBytes BIGINT DEFAULT 0,
  peakCommittedBytes BIGINT DEFAULT 0,
  peakMaxBytes BIGINT DEFAULT -1,
  peakUsagePercent DECIMAL(5,2) DEFAULT 0.00,
  usageThresholdSupported VARCHAR(1) NOT NULL DEFAULT 'N',
  usageThresholdBytes BIGINT DEFAULT 0,
  usageThresholdCount BIGINT DEFAULT 0,
  collectionUsageSupported VARCHAR(1) NOT NULL DEFAULT 'N',
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, memoryPoolId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_POOL_RES ON HUB_MONITOR_JVM_MEM_POOL (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_POOL_NAME ON HUB_MONITOR_JVM_MEM_POOL (poolName);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_POOL_TYPE ON HUB_MONITOR_JVM_MEM_POOL (poolType);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_POOL_CAT ON HUB_MONITOR_JVM_MEM_POOL (poolCategory);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_POOL_TIME ON HUB_MONITOR_JVM_MEM_POOL (collectionTime);
