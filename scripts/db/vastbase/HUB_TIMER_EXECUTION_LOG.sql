-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TIMER_EXECUTION_LOG (
  executionId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  taskId VARCHAR(32) NOT NULL,
  taskName VARCHAR(200) DEFAULT NULL,
  schedulerId VARCHAR(32) DEFAULT NULL,
  executionStartTime TIMESTAMP NOT NULL,
  executionEndTime TIMESTAMP DEFAULT NULL,
  executionDurationMs BIGINT DEFAULT NULL,
  executionStatus INT NOT NULL,
  resultSuccess VARCHAR(1) NOT NULL DEFAULT 'N',
  errorMessage TEXT DEFAULT NULL,
  errorStackTrace TEXT DEFAULT NULL,
  retryCount INT NOT NULL DEFAULT 0,
  maxRetryCount INT NOT NULL DEFAULT 0,
  executionParams TEXT DEFAULT NULL,
  executionResult TEXT DEFAULT NULL,
  executorServerName VARCHAR(100) DEFAULT NULL,
  executorServerIp VARCHAR(50) DEFAULT NULL,
  logLevel VARCHAR(10) DEFAULT NULL,
  logMessage TEXT DEFAULT NULL,
  logTimestamp TIMESTAMP DEFAULT NULL,
  executionPhase VARCHAR(50) DEFAULT NULL,
  threadName VARCHAR(100) DEFAULT NULL,
  className VARCHAR(200) DEFAULT NULL,
  methodName VARCHAR(100) DEFAULT NULL,
  exceptionClass VARCHAR(200) DEFAULT NULL,
  exceptionMessage TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, executionId)
);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_TASK ON HUB_TIMER_EXECUTION_LOG (taskId);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_NAME ON HUB_TIMER_EXECUTION_LOG (taskName);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_SCHED ON HUB_TIMER_EXECUTION_LOG (schedulerId);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_START ON HUB_TIMER_EXECUTION_LOG (executionStartTime);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_STATUS ON HUB_TIMER_EXECUTION_LOG (executionStatus);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_SUCCESS ON HUB_TIMER_EXECUTION_LOG (resultSuccess);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_LEVEL ON HUB_TIMER_EXECUTION_LOG (logLevel);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_TIME ON HUB_TIMER_EXECUTION_LOG (logTimestamp);
CREATE INDEX IF NOT EXISTS IDX_TIMER_LOG_CLEANUP ON HUB_TIMER_EXECUTION_LOG (tenantId, addTime);
