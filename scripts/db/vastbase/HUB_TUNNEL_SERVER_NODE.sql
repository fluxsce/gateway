-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TUNNEL_SERVER_NODE (
  serverNodeId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  tunnelServerId VARCHAR(32) NOT NULL,
  nodeName VARCHAR(100) NOT NULL,
  nodeType VARCHAR(20) NOT NULL DEFAULT 'static',
  proxyType VARCHAR(20) NOT NULL,
  listenAddress VARCHAR(50) NOT NULL DEFAULT '0.0.0.0',
  listenPort INT NOT NULL,
  targetAddress VARCHAR(50) NOT NULL,
  targetPort INT NOT NULL,
  customDomains TEXT DEFAULT NULL,
  subDomain VARCHAR(100) DEFAULT NULL,
  httpUser VARCHAR(50) DEFAULT NULL,
  httpPassword VARCHAR(100) DEFAULT NULL,
  hostHeaderRewrite VARCHAR(255) DEFAULT NULL,
  headers TEXT DEFAULT NULL,
  locations TEXT DEFAULT NULL,
  compression VARCHAR(1) NOT NULL DEFAULT 'Y',
  encryption VARCHAR(1) NOT NULL DEFAULT 'N',
  secretKey VARCHAR(100) DEFAULT NULL,
  healthCheckType VARCHAR(20) DEFAULT 'tcp',
  healthCheckUrl VARCHAR(255) DEFAULT NULL,
  healthCheckInterval INT DEFAULT 60,
  maxConnections INT DEFAULT 100,
  nodeStatus VARCHAR(20) NOT NULL DEFAULT 'active',
  lastHealthCheck TIMESTAMP DEFAULT NULL,
  connectionCount INT DEFAULT 0,
  totalConnections BIGINT DEFAULT 0,
  totalBytes BIGINT DEFAULT 0,
  createdTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  CONSTRAINT PK_TUNNEL_SVR_NODE PRIMARY KEY (serverNodeId),
  CONSTRAINT IDX_TUNNEL_NODE_NAME UNIQUE (nodeName),
  CONSTRAINT IDX_TUNNEL_NODE_PORT UNIQUE (listenAddress, listenPort, proxyType)
);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_NODE_TENANT ON HUB_TUNNEL_SERVER_NODE (tenantId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_NODE_SERVER ON HUB_TUNNEL_SERVER_NODE (tunnelServerId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_NODE_TYPE ON HUB_TUNNEL_SERVER_NODE (nodeType, proxyType);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_NODE_STATUS ON HUB_TUNNEL_SERVER_NODE (nodeStatus);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_NODE_HEALTH ON HUB_TUNNEL_SERVER_NODE (lastHealthCheck);
