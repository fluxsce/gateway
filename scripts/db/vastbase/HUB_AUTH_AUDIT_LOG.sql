-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_AUTH_AUDIT_LOG (
  auditId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  userId VARCHAR(32) NOT NULL,
  userName VARCHAR(100) DEFAULT NULL,
  action VARCHAR(32) NOT NULL,
  moduleCode VARCHAR(64) DEFAULT NULL,
  targetType VARCHAR(32) DEFAULT NULL,
  targetId VARCHAR(128) DEFAULT NULL,
  targetName VARCHAR(255) DEFAULT NULL,
  resourceCode VARCHAR(128) DEFAULT NULL,
  requestPath VARCHAR(255) DEFAULT NULL,
  requestMethod VARCHAR(16) DEFAULT NULL,
  clientIP VARCHAR(128) DEFAULT NULL,
  result VARCHAR(1) NOT NULL DEFAULT 'Y',
  detail TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  PRIMARY KEY (auditId)
);
CREATE INDEX IF NOT EXISTS IDX_AUTH_AUDIT_TENANT ON HUB_AUTH_AUDIT_LOG (tenantId, addTime);
CREATE INDEX IF NOT EXISTS IDX_AUTH_AUDIT_USER ON HUB_AUTH_AUDIT_LOG (userId, addTime);
CREATE INDEX IF NOT EXISTS IDX_AUTH_AUDIT_ACTION ON HUB_AUTH_AUDIT_LOG (action);
CREATE INDEX IF NOT EXISTS IDX_AUTH_AUDIT_MODULE ON HUB_AUTH_AUDIT_LOG (tenantId, moduleCode, addTime);
