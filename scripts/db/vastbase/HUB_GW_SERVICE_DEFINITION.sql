-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_SERVICE_DEFINITION (
  tenantId VARCHAR(32) NOT NULL,
  serviceDefinitionId VARCHAR(32) NOT NULL,
  serviceName VARCHAR(100) NOT NULL,
  serviceDesc VARCHAR(200) DEFAULT NULL,
  serviceType INT NOT NULL DEFAULT 0,
  proxyConfigId VARCHAR(32) NOT NULL,
  loadBalanceStrategy VARCHAR(50) NOT NULL DEFAULT 'round-robin',
  discoveryType VARCHAR(50) DEFAULT NULL,
  discoveryConfig TEXT DEFAULT NULL,
  sessionAffinity VARCHAR(1) NOT NULL DEFAULT 'N',
  stickySession VARCHAR(1) NOT NULL DEFAULT 'N',
  maxRetries INT NOT NULL DEFAULT 3,
  retryTimeoutMs INT NOT NULL DEFAULT 5000,
  enableCircuitBreaker VARCHAR(1) NOT NULL DEFAULT 'N',
  healthCheckEnabled VARCHAR(1) NOT NULL DEFAULT 'Y',
  healthCheckPath VARCHAR(200) DEFAULT '/health',
  healthCheckMethod VARCHAR(10) DEFAULT 'GET',
  healthCheckIntervalSeconds INT DEFAULT 30,
  healthCheckTimeoutMs INT DEFAULT 5000,
  healthyThreshold INT DEFAULT 2,
  unhealthyThreshold INT DEFAULT 3,
  expectedStatusCodes VARCHAR(200) DEFAULT '200',
  healthCheckHeaders TEXT DEFAULT NULL,
  loadBalancerConfig TEXT DEFAULT NULL,
  serviceMetadata TEXT DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, serviceDefinitionId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_SVC_NAME ON HUB_GW_SERVICE_DEFINITION (serviceName);
CREATE INDEX IF NOT EXISTS IDX_GW_SVC_TYPE ON HUB_GW_SERVICE_DEFINITION (serviceType);
CREATE INDEX IF NOT EXISTS IDX_GW_SVC_STRATEGY ON HUB_GW_SERVICE_DEFINITION (loadBalanceStrategy);
CREATE INDEX IF NOT EXISTS IDX_GW_SVC_HEALTH ON HUB_GW_SERVICE_DEFINITION (healthCheckEnabled);
CREATE INDEX IF NOT EXISTS IDX_GW_SVC_PROXY ON HUB_GW_SERVICE_DEFINITION (proxyConfigId);
