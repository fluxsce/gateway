-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_LOG_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  logConfigId VARCHAR(32) NOT NULL,
  configName VARCHAR(100) NOT NULL,
  configDesc VARCHAR(200) DEFAULT NULL,
  logFormat VARCHAR(50) NOT NULL DEFAULT 'JSON',
  recordRequestBody VARCHAR(1) NOT NULL DEFAULT 'N',
  recordResponseBody VARCHAR(1) NOT NULL DEFAULT 'N',
  recordHeaders VARCHAR(1) NOT NULL DEFAULT 'Y',
  maxBodySizeBytes INT NOT NULL DEFAULT 4096,
  outputTargets VARCHAR(200) NOT NULL DEFAULT 'CONSOLE',
  fileConfig TEXT DEFAULT NULL,
  databaseConfig TEXT DEFAULT NULL,
  mongoConfig TEXT DEFAULT NULL,
  elasticsearchConfig TEXT DEFAULT NULL,
  clickhouseConfig TEXT DEFAULT NULL,
  enableAsyncLogging VARCHAR(1) NOT NULL DEFAULT 'Y',
  asyncQueueSize INT NOT NULL DEFAULT 10000,
  asyncFlushIntervalMs INT NOT NULL DEFAULT 1000,
  enableBatchProcessing VARCHAR(1) NOT NULL DEFAULT 'Y',
  batchSize INT NOT NULL DEFAULT 100,
  batchTimeoutMs INT NOT NULL DEFAULT 5000,
  logRetentionDays INT NOT NULL DEFAULT 30,
  enableFileRotation VARCHAR(1) NOT NULL DEFAULT 'Y',
  maxFileSizeMB INT DEFAULT 100,
  maxFileCount INT DEFAULT 10,
  rotationPattern VARCHAR(100) DEFAULT 'DAILY',
  enableSensitiveDataMasking VARCHAR(1) NOT NULL DEFAULT 'Y',
  sensitiveFields TEXT DEFAULT NULL,
  maskingPattern VARCHAR(100) DEFAULT '***',
  bufferSize INT NOT NULL DEFAULT 8192,
  flushThreshold INT NOT NULL DEFAULT 100,
  configPriority INT NOT NULL DEFAULT 0,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, logConfigId)
);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_LOG_CONFIG_name ON HUB_GW_LOG_CONFIG (configName);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_LOG_CONFIG_priority ON HUB_GW_LOG_CONFIG (configPriority);
