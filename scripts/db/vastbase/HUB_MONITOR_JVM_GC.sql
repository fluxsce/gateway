-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_GC (
  gcSnapshotId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  collectionCount BIGINT NOT NULL DEFAULT 0,
  collectionTimeMs BIGINT NOT NULL DEFAULT 0,
  s0c BIGINT DEFAULT 0,
  s1c BIGINT DEFAULT 0,
  s0u BIGINT DEFAULT 0,
  s1u BIGINT DEFAULT 0,
  ec BIGINT DEFAULT 0,
  eu BIGINT DEFAULT 0,
  oc BIGINT DEFAULT 0,
  ou BIGINT DEFAULT 0,
  mc BIGINT DEFAULT 0,
  mu BIGINT DEFAULT 0,
  ccsc BIGINT DEFAULT 0,
  ccsu BIGINT DEFAULT 0,
  ygc BIGINT DEFAULT 0,
  ygct DECIMAL(10,3) DEFAULT 0.000,
  fgc BIGINT DEFAULT 0,
  fgct DECIMAL(10,3) DEFAULT 0.000,
  gct DECIMAL(10,3) DEFAULT 0.000,
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, gcSnapshotId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_GC_RES ON HUB_MONITOR_JVM_GC (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_GC_TIME ON HUB_MONITOR_JVM_GC (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_GC_RES_TIME ON HUB_MONITOR_JVM_GC (jvmResourceId, collectionTime);
