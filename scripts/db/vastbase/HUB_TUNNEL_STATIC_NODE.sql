-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TUNNEL_STATIC_NODE (
  tunnelStaticNodeId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  tunnelStaticServerId VARCHAR(32) NOT NULL,
  nodeName VARCHAR(100) NOT NULL,
  nodeDescription VARCHAR(500) DEFAULT NULL,
  targetAddress VARCHAR(50) NOT NULL,
  targetPort INT NOT NULL,
  proxyType VARCHAR(20) NOT NULL DEFAULT 'tcp',
  maxConnections INT DEFAULT 100,
  connectionTimeout INT DEFAULT 30,
  readTimeout INT DEFAULT 30,
  writeTimeout INT DEFAULT 30,
  retryCount INT DEFAULT 3,
  retryInterval INT DEFAULT 5,
  compression VARCHAR(1) NOT NULL DEFAULT 'N',
  encryption VARCHAR(1) NOT NULL DEFAULT 'N',
  secretKey VARCHAR(100) DEFAULT NULL,
  customHeaders TEXT DEFAULT NULL,
  nodeStatus VARCHAR(20) NOT NULL DEFAULT 'active',
  lastHealthCheck TIMESTAMP DEFAULT NULL,
  healthCheckStatus VARCHAR(20) DEFAULT 'unknown',
  currentConnectionCount INT DEFAULT 0,
  totalConnectionCount BIGINT DEFAULT 0,
  totalBytesReceived BIGINT DEFAULT 0,
  totalBytesSent BIGINT DEFAULT 0,
  failureCount INT DEFAULT 0,
  lastFailureTime TIMESTAMP DEFAULT NULL,
  nodeConfig TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  CONSTRAINT PK_TUNNEL_STATIC_NODE PRIMARY KEY (tunnelStaticNodeId),
  CONSTRAINT IDX_TUNNEL_STATIC_NODE_NAME UNIQUE (nodeName),
  CONSTRAINT IDX_TUNNEL_STATIC_NODE_TARGET UNIQUE (tunnelStaticServerId, targetAddress, targetPort)
);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_NODE_TENANT ON HUB_TUNNEL_STATIC_NODE (tenantId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_NODE_SERVER ON HUB_TUNNEL_STATIC_NODE (tunnelStaticServerId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_NODE_TYPE ON HUB_TUNNEL_STATIC_NODE (proxyType);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_NODE_STATUS ON HUB_TUNNEL_STATIC_NODE (nodeStatus);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_NODE_HEALTH ON HUB_TUNNEL_STATIC_NODE (healthCheckStatus, lastHealthCheck);
