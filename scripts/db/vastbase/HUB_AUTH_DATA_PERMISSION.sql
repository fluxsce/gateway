-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_AUTH_DATA_PERMISSION (
  dataPermissionId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  userId VARCHAR(32) DEFAULT NULL,
  roleId VARCHAR(32) DEFAULT NULL,
  resourceType VARCHAR(50) NOT NULL,
  resourceCode VARCHAR(100) NOT NULL,
  scopeValue TEXT DEFAULT NULL,
  filterCondition TEXT DEFAULT NULL,
  columnPermissions TEXT DEFAULT NULL,
  operationPermissions VARCHAR(50) DEFAULT 'read',
  effectiveTime TIMESTAMP DEFAULT NULL,
  expireTime TIMESTAMP DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, dataPermissionId)
);
CREATE INDEX IF NOT EXISTS IDX_AUTH_DATA_PERM_USER ON HUB_AUTH_DATA_PERMISSION (tenantId, userId);
CREATE INDEX IF NOT EXISTS IDX_AUTH_DATA_PERM_ROLE ON HUB_AUTH_DATA_PERMISSION (tenantId, roleId);
CREATE INDEX IF NOT EXISTS IDX_AUTH_DATA_PERM_RESOURCE ON HUB_AUTH_DATA_PERMISSION (resourceType, resourceCode);
CREATE INDEX IF NOT EXISTS IDX_AUTH_DATA_PERM_EXPIRE ON HUB_AUTH_DATA_PERMISSION (expireTime);
