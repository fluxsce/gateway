-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TOOL_CONFIG (
  toolConfigId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  toolName VARCHAR(100) NOT NULL,
  toolType VARCHAR(50) NOT NULL,
  toolVersion VARCHAR(20) DEFAULT NULL,
  configName VARCHAR(100) NOT NULL,
  configDescription VARCHAR(500) DEFAULT NULL,
  configGroupId VARCHAR(32) DEFAULT NULL,
  configGroupName VARCHAR(100) DEFAULT NULL,
  hostAddress VARCHAR(255) DEFAULT NULL,
  portNumber INT DEFAULT NULL,
  protocolType VARCHAR(20) DEFAULT NULL,
  authType VARCHAR(50) DEFAULT NULL,
  userName VARCHAR(100) DEFAULT NULL,
  passwordEncrypted VARCHAR(500) DEFAULT NULL,
  keyFilePath VARCHAR(500) DEFAULT NULL,
  keyFileContent TEXT DEFAULT NULL,
  configParameters TEXT DEFAULT NULL,
  environmentVariables TEXT DEFAULT NULL,
  customSettings TEXT DEFAULT NULL,
  configStatus VARCHAR(1) NOT NULL DEFAULT 'Y',
  defaultFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  priorityLevel INT DEFAULT 100,
  encryptionType VARCHAR(50) DEFAULT NULL,
  encryptionKey VARCHAR(100) DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, toolConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_NAME ON HUB_TOOL_CONFIG (toolName);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_TYPE ON HUB_TOOL_CONFIG (toolType);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_CFGNAME ON HUB_TOOL_CONFIG (configName);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_GROUP ON HUB_TOOL_CONFIG (configGroupId);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_STATUS ON HUB_TOOL_CONFIG (configStatus);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_DEFAULT ON HUB_TOOL_CONFIG (defaultFlag);
CREATE INDEX IF NOT EXISTS IDX_TOOL_CONFIG_ACTIVE ON HUB_TOOL_CONFIG (activeFlag);
