-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_SERVICE_AUTH_TOKEN (
  tokenId VARCHAR(64) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  tokenValue VARCHAR(256) NOT NULL,
  userId VARCHAR(64) NOT NULL,
  tokenName VARCHAR(128) DEFAULT NULL,
  expireTime TIMESTAMP DEFAULT NULL,
  statusFlag CHAR(1) NOT NULL DEFAULT 'Y',
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(64) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(64) NOT NULL,
  oprSeqFlag VARCHAR(64) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag CHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(512) DEFAULT NULL,
  extProperty TEXT,
  PRIMARY KEY (tenantId, tokenId),
  CONSTRAINT UK_SC_AUTH_TOKEN_VALUE UNIQUE (tokenValue)
);
CREATE INDEX IF NOT EXISTS IDX_SC_AUTH_TOKEN_USER ON HUB_SERVICE_AUTH_TOKEN (userId);
