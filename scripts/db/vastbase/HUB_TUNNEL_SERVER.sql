-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TUNNEL_SERVER (
  tunnelServerId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  serverName VARCHAR(100) NOT NULL,
  serverDescription VARCHAR(500) DEFAULT NULL,
  controlAddress VARCHAR(50) NOT NULL DEFAULT '0.0.0.0',
  controlPort INT NOT NULL DEFAULT 7000,
  dashboardPort INT DEFAULT 7500,
  vhostHttpPort INT DEFAULT 80,
  vhostHttpsPort INT DEFAULT 443,
  maxClients INT NOT NULL DEFAULT 1000,
  tokenAuth VARCHAR(1) NOT NULL DEFAULT 'Y',
  authToken VARCHAR(100) DEFAULT NULL,
  tlsEnable VARCHAR(1) NOT NULL DEFAULT 'N',
  tlsCertFile VARCHAR(255) DEFAULT NULL,
  tlsKeyFile VARCHAR(255) DEFAULT NULL,
  heartbeatInterval INT NOT NULL DEFAULT 30,
  heartbeatTimeout INT NOT NULL DEFAULT 90,
  logLevel VARCHAR(10) NOT NULL DEFAULT 'info',
  maxPortsPerClient INT DEFAULT 10,
  allowPorts TEXT DEFAULT NULL,
  serverStatus VARCHAR(20) NOT NULL DEFAULT 'stopped',
  startTime TIMESTAMP DEFAULT NULL,
  configVersion VARCHAR(32) DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  CONSTRAINT PK_TUNNEL_SERVER PRIMARY KEY (tunnelServerId),
  CONSTRAINT IDX_TUNNEL_SVR_NAME UNIQUE (serverName)
);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVR_TENANT ON HUB_TUNNEL_SERVER (tenantId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVR_CTRL ON HUB_TUNNEL_SERVER (controlAddress, controlPort);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVR_STATUS ON HUB_TUNNEL_SERVER (serverStatus);
