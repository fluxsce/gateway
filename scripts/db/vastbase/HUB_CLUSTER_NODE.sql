-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_CLUSTER_NODE (
  nodeId VARCHAR(64) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  nodeIp VARCHAR(100) DEFAULT NULL,
  hostname VARCHAR(255) DEFAULT NULL,
  startedTime TIMESTAMP NOT NULL,
  lastSeenTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(64) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(64) NOT NULL,
  oprSeqFlag VARCHAR(64) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText TEXT DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(64) DEFAULT NULL,
  reserved2 VARCHAR(64) DEFAULT NULL,
  reserved3 VARCHAR(100) DEFAULT NULL,
  reserved4 VARCHAR(100) DEFAULT NULL,
  reserved5 VARCHAR(255) DEFAULT NULL,
  PRIMARY KEY (tenantId, nodeId)
);
CREATE INDEX IF NOT EXISTS IDX_CLS_NODE_SEEN ON HUB_CLUSTER_NODE (tenantId, lastSeenTime);
