-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_APP_DATA (
  appDataId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  dataType VARCHAR(50) NOT NULL,
  dataName VARCHAR(100) NOT NULL,
  dataCategory VARCHAR(50) DEFAULT NULL,
  dataJson TEXT NOT NULL,
  primaryValue DECIMAL(20,4) DEFAULT NULL,
  secondaryValue DECIMAL(20,4) DEFAULT NULL,
  statusValue VARCHAR(50) DEFAULT NULL,
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  healthGrade VARCHAR(20) DEFAULT NULL,
  requiresAttentionFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  tagsJson TEXT DEFAULT NULL,
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, appDataId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_RES ON HUB_MONITOR_APP_DATA (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_TYPE ON HUB_MONITOR_APP_DATA (dataType);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_NAME ON HUB_MONITOR_APP_DATA (dataName);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_TIME ON HUB_MONITOR_APP_DATA (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_HEALTH ON HUB_MONITOR_APP_DATA (healthyFlag, requiresAttentionFlag);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_PRIMARY ON HUB_MONITOR_APP_DATA (primaryValue);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_STATUS ON HUB_MONITOR_APP_DATA (statusValue);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_APP_DATA_RES_TYPE_NAME ON HUB_MONITOR_APP_DATA (jvmResourceId, dataType, dataName, collectionTime);
