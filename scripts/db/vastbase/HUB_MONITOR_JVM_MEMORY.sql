-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_MEMORY (
  jvmMemoryId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  memoryType VARCHAR(20) NOT NULL,
  initMemoryBytes BIGINT NOT NULL DEFAULT 0,
  usedMemoryBytes BIGINT NOT NULL DEFAULT 0,
  committedMemoryBytes BIGINT NOT NULL DEFAULT 0,
  maxMemoryBytes BIGINT NOT NULL DEFAULT -1,
  usagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, jvmMemoryId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_MEM_RES ON HUB_MONITOR_JVM_MEMORY (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_MEM_TYPE ON HUB_MONITOR_JVM_MEMORY (memoryType);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_MEM_TIME ON HUB_MONITOR_JVM_MEMORY (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_MEM_USAGE ON HUB_MONITOR_JVM_MEMORY (usagePercent);
