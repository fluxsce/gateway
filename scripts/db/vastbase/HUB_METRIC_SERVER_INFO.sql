-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_SERVER_INFO (
  metricServerId VARCHAR(64) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  hostname VARCHAR(255) NOT NULL,
  osType VARCHAR(100) NOT NULL,
  osVersion VARCHAR(255) NOT NULL,
  kernelVersion VARCHAR(255) DEFAULT NULL,
  architecture VARCHAR(100) NOT NULL,
  bootTime TIMESTAMP NOT NULL,
  ipAddress VARCHAR(45) DEFAULT NULL,
  macAddress VARCHAR(50) DEFAULT NULL,
  serverLocation VARCHAR(255) DEFAULT NULL,
  serverType VARCHAR(50) DEFAULT NULL,
  lastUpdateTime TIMESTAMP NOT NULL,
  networkInfo TEXT DEFAULT NULL,
  systemInfo TEXT DEFAULT NULL,
  hardwareInfo TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(64) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(64) NOT NULL,
  oprSeqFlag VARCHAR(64) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText TEXT DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricServerId),
  CONSTRAINT IDX_METRIC_SERVER_HOST UNIQUE (hostname)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_SERVER_OS ON HUB_METRIC_SERVER_INFO (osType);
CREATE INDEX IF NOT EXISTS IDX_METRIC_SERVER_IP ON HUB_METRIC_SERVER_INFO (ipAddress);
CREATE INDEX IF NOT EXISTS IDX_METRIC_SERVER_TYPE ON HUB_METRIC_SERVER_INFO (serverType);
CREATE INDEX IF NOT EXISTS IDX_METRIC_SERVER_ACTIVE ON HUB_METRIC_SERVER_INFO (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_SERVER_UPDATE ON HUB_METRIC_SERVER_INFO (lastUpdateTime);

ALTER TABLE HUB_METRIC_SERVER_INFO DROP CONSTRAINT IF EXISTS IDX_METRIC_SERVER_HOST;
