-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_ROUTE_ASSERTION (
  tenantId VARCHAR(32) NOT NULL,
  routeAssertionId VARCHAR(32) NOT NULL,
  routeConfigId VARCHAR(32) NOT NULL,
  assertionName VARCHAR(100) NOT NULL,
  assertionType VARCHAR(50) NOT NULL,
  assertionOperator VARCHAR(20) NOT NULL DEFAULT 'EQUAL',
  fieldName VARCHAR(100) DEFAULT NULL,
  expectedValue VARCHAR(500) DEFAULT NULL,
  patternValue VARCHAR(500) DEFAULT NULL,
  caseSensitive VARCHAR(1) NOT NULL DEFAULT 'Y',
  assertionOrder INT NOT NULL DEFAULT 0,
  isRequired VARCHAR(1) NOT NULL DEFAULT 'Y',
  assertionDesc VARCHAR(200) DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, routeAssertionId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_ASSERT_ROUTE ON HUB_GW_ROUTE_ASSERTION (routeConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_ASSERT_TYPE ON HUB_GW_ROUTE_ASSERTION (assertionType);
CREATE INDEX IF NOT EXISTS IDX_GW_ASSERT_ORDER ON HUB_GW_ROUTE_ASSERTION (assertionOrder);
