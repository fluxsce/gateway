-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_PROCESS_LOG (
  metricProcessLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  processId INT NOT NULL,
  parentProcessId INT DEFAULT NULL,
  processName VARCHAR(200) NOT NULL,
  processStatus VARCHAR(50) NOT NULL,
  createTime TIMESTAMP NOT NULL,
  runTime BIGINT NOT NULL DEFAULT 0,
  memoryUsage BIGINT NOT NULL DEFAULT 0,
  memoryPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  cpuPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  threadCount INT NOT NULL DEFAULT 0,
  fileDescriptorCount INT NOT NULL DEFAULT 0,
  commandLine TEXT DEFAULT NULL,
  executablePath VARCHAR(500) DEFAULT NULL,
  workingDirectory VARCHAR(500) DEFAULT NULL,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricProcessLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_SERVER ON HUB_METRIC_PROCESS_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_TIME ON HUB_METRIC_PROCESS_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_PID ON HUB_METRIC_PROCESS_LOG (processId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_NAME ON HUB_METRIC_PROCESS_LOG (processName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_STATUS ON HUB_METRIC_PROCESS_LOG (processStatus);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_ACTIVE ON HUB_METRIC_PROCESS_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_SRV_TIME ON HUB_METRIC_PROCESS_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_SRV_PID ON HUB_METRIC_PROCESS_LOG (metricServerId, processId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROCESS_TNT_TIME ON HUB_METRIC_PROCESS_LOG (tenantId, collectTime);
