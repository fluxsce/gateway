-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_STATIC_HOST_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  staticHostConfigId VARCHAR(32) NOT NULL,
  routeConfigId VARCHAR(32) NOT NULL,
  configName VARCHAR(100) NOT NULL,
  rootDirectory VARCHAR(500) NOT NULL,
  stripRoutePrefix VARCHAR(1) NOT NULL DEFAULT 'Y',
  indexFiles TEXT DEFAULT NULL,
  rewriteRules TEXT DEFAULT NULL,
  spaFallback VARCHAR(1) NOT NULL DEFAULT 'N',
  cacheControlMaxAge INT NOT NULL DEFAULT 3600,
  allowedExtensions TEXT DEFAULT NULL,
  maxFileSizeBytes BIGINT NOT NULL DEFAULT 0,
  followSymlinks VARCHAR(1) NOT NULL DEFAULT 'N',
  enablePrecompress VARCHAR(1) NOT NULL DEFAULT 'Y',
  errorPage404 VARCHAR(200) DEFAULT NULL,
  errorPage403 VARCHAR(200) DEFAULT NULL,
  configPriority INT NOT NULL DEFAULT 0,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, staticHostConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_STATIC_ROUTE ON HUB_GW_STATIC_HOST_CONFIG (routeConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_STATIC_PRIORITY ON HUB_GW_STATIC_HOST_CONFIG (configPriority);
CREATE INDEX IF NOT EXISTS IDX_GW_STATIC_ACTIVE ON HUB_GW_STATIC_HOST_CONFIG (activeFlag);

