-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_FILTER_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  filterConfigId VARCHAR(32) NOT NULL,
  gatewayInstanceId VARCHAR(32) DEFAULT NULL,
  routeConfigId VARCHAR(32) DEFAULT NULL,
  filterName VARCHAR(100) NOT NULL,
  filterType VARCHAR(50) NOT NULL,
  filterAction VARCHAR(50) NOT NULL,
  filterOrder INT NOT NULL DEFAULT 0,
  filterConfig TEXT NOT NULL,
  filterDesc VARCHAR(200) DEFAULT NULL,
  configId VARCHAR(100) DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, filterConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_FILTER_INST ON HUB_GW_FILTER_CONFIG (gatewayInstanceId);
CREATE INDEX IF NOT EXISTS IDX_GW_FILTER_ROUTE ON HUB_GW_FILTER_CONFIG (routeConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_FILTER_TYPE ON HUB_GW_FILTER_CONFIG (filterType);
CREATE INDEX IF NOT EXISTS IDX_GW_FILTER_ACTION ON HUB_GW_FILTER_CONFIG (filterAction);
CREATE INDEX IF NOT EXISTS IDX_GW_FILTER_ORDER ON HUB_GW_FILTER_CONFIG (filterOrder);
CREATE INDEX IF NOT EXISTS IDX_GW_FILTER_ACTIVE ON HUB_GW_FILTER_CONFIG (activeFlag);
