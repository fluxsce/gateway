-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_SERVICE_NODE (
  nodeId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  namespaceId VARCHAR(32) NOT NULL,
  groupName VARCHAR(64) NOT NULL,
  serviceName VARCHAR(100) NOT NULL,
  ipAddress VARCHAR(50) NOT NULL,
  portNumber INT NOT NULL,
  instanceStatus VARCHAR(20) NOT NULL DEFAULT 'UP',
  healthyStatus VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
  ephemeral VARCHAR(1) NOT NULL DEFAULT 'Y',
  weight DECIMAL(6,2) NOT NULL DEFAULT 1.00,
  metadataJson TEXT DEFAULT NULL,
  registerTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lastBeatTime TIMESTAMP DEFAULT NULL,
  lastCheckTime TIMESTAMP DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  PRIMARY KEY (tenantId, nodeId),
  CONSTRAINT IDX_SVC_NODE_UNIQUE UNIQUE (tenantId, namespaceId, groupName, serviceName, ipAddress, portNumber)
);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_SERVICE ON HUB_SERVICE_NODE (tenantId, namespaceId, groupName, serviceName);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_SERVICE_NAME ON HUB_SERVICE_NODE (tenantId, serviceName);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_NS_ID ON HUB_SERVICE_NODE (tenantId, namespaceId);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_GROUP_NAME ON HUB_SERVICE_NODE (tenantId, namespaceId, groupName);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_IP_PORT ON HUB_SERVICE_NODE (ipAddress, portNumber);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_STATUS ON HUB_SERVICE_NODE (instanceStatus);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_HEALTHY ON HUB_SERVICE_NODE (healthyStatus);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_EPHEMERAL ON HUB_SERVICE_NODE (ephemeral);
CREATE INDEX IF NOT EXISTS IDX_SVC_NODE_ACTIVE ON HUB_SERVICE_NODE (activeFlag);
