-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_DISK_PART_LOG (
  metricDiskPartitionLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  deviceName VARCHAR(100) NOT NULL,
  mountPoint VARCHAR(200) NOT NULL,
  fileSystem VARCHAR(50) NOT NULL,
  totalSpace BIGINT NOT NULL DEFAULT 0,
  usedSpace BIGINT NOT NULL DEFAULT 0,
  freeSpace BIGINT NOT NULL DEFAULT 0,
  usagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  inodesTotal BIGINT NOT NULL DEFAULT 0,
  inodesUsed BIGINT NOT NULL DEFAULT 0,
  inodesFree BIGINT NOT NULL DEFAULT 0,
  inodesUsagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricDiskPartitionLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_SERVER ON HUB_METRIC_DISK_PART_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_TIME ON HUB_METRIC_DISK_PART_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_DEVICE ON HUB_METRIC_DISK_PART_LOG (deviceName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_USAGE ON HUB_METRIC_DISK_PART_LOG (usagePercent);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_ACTIVE ON HUB_METRIC_DISK_PART_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_SRV_TIME ON HUB_METRIC_DISK_PART_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_SRV_DEV ON HUB_METRIC_DISK_PART_LOG (metricServerId, deviceName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_PART_TNT_TIME ON HUB_METRIC_DISK_PART_LOG (tenantId, collectTime);
