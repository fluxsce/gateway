-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_RESOURCE (
  jvmResourceId VARCHAR(100) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  serviceGroupId VARCHAR(32) NOT NULL,
  applicationName VARCHAR(100) NOT NULL,
  groupName VARCHAR(100) NOT NULL,
  hostName VARCHAR(100) DEFAULT NULL,
  hostIpAddress VARCHAR(50) DEFAULT NULL,
  collectionTime TIMESTAMP NOT NULL,
  jvmStartTime TIMESTAMP NOT NULL,
  jvmUptimeMs BIGINT NOT NULL DEFAULT 0,
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  healthGrade VARCHAR(20) DEFAULT NULL,
  requiresAttentionFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  summaryText VARCHAR(500) DEFAULT NULL,
  systemPropertiesJson TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, serviceGroupId, jvmResourceId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_JVM_APP ON HUB_MONITOR_JVM_RESOURCE (applicationName);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_JVM_TIME ON HUB_MONITOR_JVM_RESOURCE (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_JVM_HEALTH ON HUB_MONITOR_JVM_RESOURCE (healthyFlag, requiresAttentionFlag);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_JVM_HOST ON HUB_MONITOR_JVM_RESOURCE (hostIpAddress);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_JVM_GROUP ON HUB_MONITOR_JVM_RESOURCE (serviceGroupId, groupName);
