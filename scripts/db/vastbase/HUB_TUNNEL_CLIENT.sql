-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TUNNEL_CLIENT (
  tunnelClientId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  userId VARCHAR(32) NOT NULL,
  clientName VARCHAR(100) NOT NULL,
  clientDescription VARCHAR(500) DEFAULT NULL,
  clientVersion VARCHAR(20) DEFAULT NULL,
  operatingSystem VARCHAR(50) DEFAULT NULL,
  clientIpAddress VARCHAR(50) DEFAULT NULL,
  clientMacAddress VARCHAR(20) DEFAULT NULL,
  serverAddress VARCHAR(100) NOT NULL,
  serverPort INT NOT NULL DEFAULT 7000,
  authToken VARCHAR(100) NOT NULL,
  tlsEnable VARCHAR(1) NOT NULL DEFAULT 'N',
  autoReconnect VARCHAR(1) NOT NULL DEFAULT 'Y',
  maxRetries INT NOT NULL DEFAULT 5,
  retryInterval INT NOT NULL DEFAULT 20,
  heartbeatInterval INT NOT NULL DEFAULT 30,
  heartbeatTimeout INT NOT NULL DEFAULT 90,
  connectionStatus VARCHAR(20) NOT NULL DEFAULT 'disconnected',
  lastConnectTime TIMESTAMP DEFAULT NULL,
  lastDisconnectTime TIMESTAMP DEFAULT NULL,
  totalConnectTime BIGINT DEFAULT 0,
  reconnectCount INT DEFAULT 0,
  serviceCount INT DEFAULT 0,
  lastHeartbeat TIMESTAMP DEFAULT NULL,
  clientConfig TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  CONSTRAINT PK_TUNNEL_CLIENT PRIMARY KEY (tunnelClientId),
  CONSTRAINT IDX_TUNNEL_CLIENT_NAME UNIQUE (clientName)
);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_CLIENT_TENANT ON HUB_TUNNEL_CLIENT (tenantId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_CLIENT_USER ON HUB_TUNNEL_CLIENT (userId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_CLIENT_STATUS ON HUB_TUNNEL_CLIENT (connectionStatus);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_CLIENT_IP ON HUB_TUNNEL_CLIENT (clientIpAddress);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_CLIENT_HB ON HUB_TUNNEL_CLIENT (lastHeartbeat);
