-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_ACCESS_LOG (
  tenantId VARCHAR(32) NOT NULL,
  traceId VARCHAR(64) NOT NULL,
  gatewayInstanceId VARCHAR(32) NOT NULL,
  gatewayInstanceName VARCHAR(300) DEFAULT NULL,
  gatewayNodeIp VARCHAR(50) NOT NULL,
  routeConfigId VARCHAR(32) DEFAULT NULL,
  routeName VARCHAR(300) DEFAULT NULL,
  serviceDefinitionId VARCHAR(32) DEFAULT NULL,
  serviceName VARCHAR(300) DEFAULT NULL,
  proxyType VARCHAR(50) DEFAULT NULL,
  logConfigId VARCHAR(32) DEFAULT NULL,
  requestMethod VARCHAR(10) NOT NULL,
  requestPath VARCHAR(1000) NOT NULL,
  requestQuery TEXT DEFAULT NULL,
  requestSize INT DEFAULT 0,
  requestHeaders TEXT DEFAULT NULL,
  requestBody TEXT DEFAULT NULL,
  clientIpAddress VARCHAR(50) NOT NULL,
  clientPort INT DEFAULT NULL,
  userAgent VARCHAR(1000) DEFAULT NULL,
  referer VARCHAR(1000) DEFAULT NULL,
  userIdentifier VARCHAR(100) DEFAULT NULL,
  gatewayStartProcessingTime TIMESTAMP(3) NOT NULL,
  backendRequestStartTime TIMESTAMP(3) DEFAULT NULL,
  backendResponseReceivedTime TIMESTAMP(3) DEFAULT NULL,
  gatewayFinishedProcessingTime TIMESTAMP(3) DEFAULT NULL,
  totalProcessingTimeMs INT DEFAULT NULL,
  gatewayProcessingTimeMs INT DEFAULT NULL,
  backendResponseTimeMs INT DEFAULT NULL,
  gatewayStatusCode INT NOT NULL,
  backendStatusCode INT DEFAULT NULL,
  responseSize INT DEFAULT 0,
  responseHeaders TEXT DEFAULT NULL,
  responseBody TEXT DEFAULT NULL,
  matchedRoute VARCHAR(500) DEFAULT NULL,
  forwardAddress TEXT DEFAULT NULL,
  forwardMethod VARCHAR(10) DEFAULT NULL,
  forwardParams TEXT DEFAULT NULL,
  forwardHeaders TEXT DEFAULT NULL,
  forwardBody TEXT DEFAULT NULL,
  loadBalancerDecision VARCHAR(500) DEFAULT NULL,
  errorMessage TEXT DEFAULT NULL,
  errorCode VARCHAR(100) DEFAULT NULL,
  parentTraceId VARCHAR(100) DEFAULT NULL,
  resetFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  retryCount INT NOT NULL DEFAULT 0,
  resetCount INT NOT NULL DEFAULT 0,
  logLevel VARCHAR(20) NOT NULL DEFAULT 'INFO',
  logType VARCHAR(50) NOT NULL DEFAULT 'ACCESS',
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, traceId)
);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_ACCESS_LOG_time_instance ON HUB_GW_ACCESS_LOG (gatewayStartProcessingTime, gatewayInstanceId);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_ACCESS_LOG_instance_name ON HUB_GW_ACCESS_LOG (gatewayInstanceName, gatewayStartProcessingTime);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_ACCESS_LOG_route_name ON HUB_GW_ACCESS_LOG (routeName, gatewayStartProcessingTime);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_ACCESS_LOG_service_name ON HUB_GW_ACCESS_LOG (serviceName, gatewayStartProcessingTime);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_ACCESS_LOG_status_time ON HUB_GW_ACCESS_LOG (gatewayStatusCode, gatewayStartProcessingTime);
CREATE INDEX IF NOT EXISTS idx_HUB_GW_ACCESS_LOG_proxy_type ON HUB_GW_ACCESS_LOG (proxyType, gatewayStartProcessingTime);

CREATE INDEX idx_HUB_GW_ACCESS_LOG_instance_time ON HUB_GW_ACCESS_LOG (gatewayInstanceId, gatewayStartProcessingTime);
