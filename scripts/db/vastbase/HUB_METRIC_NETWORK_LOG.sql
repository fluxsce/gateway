-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_NETWORK_LOG (
  metricNetworkLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  interfaceName VARCHAR(100) NOT NULL,
  hardwareAddr VARCHAR(50) DEFAULT NULL,
  ipAddresses TEXT DEFAULT NULL,
  interfaceStatus VARCHAR(20) NOT NULL,
  interfaceType VARCHAR(50) DEFAULT NULL,
  bytesReceived BIGINT NOT NULL DEFAULT 0,
  bytesSent BIGINT NOT NULL DEFAULT 0,
  packetsReceived BIGINT NOT NULL DEFAULT 0,
  packetsSent BIGINT NOT NULL DEFAULT 0,
  errorsReceived BIGINT NOT NULL DEFAULT 0,
  errorsSent BIGINT NOT NULL DEFAULT 0,
  droppedReceived BIGINT NOT NULL DEFAULT 0,
  droppedSent BIGINT NOT NULL DEFAULT 0,
  receiveRate DECIMAL(20,2) DEFAULT 0,
  sendRate DECIMAL(20,2) DEFAULT 0,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricNetworkLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_SERVER ON HUB_METRIC_NETWORK_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_TIME ON HUB_METRIC_NETWORK_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_INTERFACE ON HUB_METRIC_NETWORK_LOG (interfaceName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_STATUS ON HUB_METRIC_NETWORK_LOG (interfaceStatus);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_ACTIVE ON HUB_METRIC_NETWORK_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_SRV_TIME ON HUB_METRIC_NETWORK_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_SRV_INT ON HUB_METRIC_NETWORK_LOG (metricServerId, interfaceName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_NETWORK_TNT_TIME ON HUB_METRIC_NETWORK_LOG (tenantId, collectTime);
