-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_CLASS (
  classLoadingId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  loadedClassCount INT NOT NULL DEFAULT 0,
  totalLoadedClassCount BIGINT NOT NULL DEFAULT 0,
  unloadedClassCount BIGINT NOT NULL DEFAULT 0,
  classUnloadRatePercent DECIMAL(5,2) DEFAULT 0.00,
  classRetentionRatePercent DECIMAL(5,2) DEFAULT 0.00,
  verboseClassLoading VARCHAR(1) NOT NULL DEFAULT 'N',
  loadingRatePerHour DECIMAL(10,2) DEFAULT 0.00,
  loadingEfficiency DECIMAL(5,2) DEFAULT 0.00,
  memoryEfficiency VARCHAR(100) DEFAULT NULL,
  loaderHealth VARCHAR(50) DEFAULT NULL,
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  healthGrade VARCHAR(20) DEFAULT NULL,
  requiresAttentionFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  potentialIssuesJson TEXT DEFAULT NULL,
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, classLoadingId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_CLS_RES ON HUB_MONITOR_JVM_CLASS (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_CLS_TIME ON HUB_MONITOR_JVM_CLASS (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_CLS_HEALTH ON HUB_MONITOR_JVM_CLASS (healthyFlag, requiresAttentionFlag);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_CLS_COUNT ON HUB_MONITOR_JVM_CLASS (loadedClassCount);
