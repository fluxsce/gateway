-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_CLUSTER_EVENT_ACK (
  ackId VARCHAR(64) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  eventId VARCHAR(64) NOT NULL,
  nodeId VARCHAR(100) NOT NULL,
  nodeIp VARCHAR(100) DEFAULT NULL,
  ackStatus VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  processTime TIMESTAMP DEFAULT NULL,
  resultMessage VARCHAR(2000) DEFAULT NULL,
  retryCount INT NOT NULL DEFAULT 0,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(64) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(64) NOT NULL,
  oprSeqFlag VARCHAR(64) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText TEXT DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, ackId)
);
CREATE INDEX IF NOT EXISTS IDX_CLS_ACK_EVT_NODE ON HUB_CLUSTER_EVENT_ACK (eventId, nodeId, ackStatus);
CREATE INDEX IF NOT EXISTS IDX_CLS_ACK_NODE ON HUB_CLUSTER_EVENT_ACK (nodeId, ackStatus, processTime);
CREATE INDEX IF NOT EXISTS IDX_CLS_ACK_CLEANUP ON HUB_CLUSTER_EVENT_ACK (tenantId, addTime);
