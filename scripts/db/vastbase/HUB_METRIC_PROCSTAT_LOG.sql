-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_PROCSTAT_LOG (
  metricProcessStatsLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  runningCount INT NOT NULL DEFAULT 0,
  sleepingCount INT NOT NULL DEFAULT 0,
  stoppedCount INT NOT NULL DEFAULT 0,
  zombieCount INT NOT NULL DEFAULT 0,
  totalCount INT NOT NULL DEFAULT 0,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricProcessStatsLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROC_STATS_SERVER ON HUB_METRIC_PROCSTAT_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROC_STATS_TIME ON HUB_METRIC_PROCSTAT_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROC_STATS_ACTIVE ON HUB_METRIC_PROCSTAT_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROC_STATS_SRV_TIME ON HUB_METRIC_PROCSTAT_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_PROC_STATS_TNT_TIME ON HUB_METRIC_PROCSTAT_LOG (tenantId, collectTime);
