-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_MEMORY_LOG (
  metricMemoryLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  totalMemory BIGINT NOT NULL DEFAULT 0,
  availableMemory BIGINT NOT NULL DEFAULT 0,
  usedMemory BIGINT NOT NULL DEFAULT 0,
  usagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  freeMemory BIGINT NOT NULL DEFAULT 0,
  cachedMemory BIGINT NOT NULL DEFAULT 0,
  buffersMemory BIGINT NOT NULL DEFAULT 0,
  sharedMemory BIGINT NOT NULL DEFAULT 0,
  swapTotal BIGINT NOT NULL DEFAULT 0,
  swapUsed BIGINT NOT NULL DEFAULT 0,
  swapFree BIGINT NOT NULL DEFAULT 0,
  swapUsagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricMemoryLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_MEMORY_SERVER ON HUB_METRIC_MEMORY_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_MEMORY_TIME ON HUB_METRIC_MEMORY_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_MEMORY_USAGE ON HUB_METRIC_MEMORY_LOG (usagePercent);
CREATE INDEX IF NOT EXISTS IDX_METRIC_MEMORY_ACTIVE ON HUB_METRIC_MEMORY_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_MEMORY_SRV_TIME ON HUB_METRIC_MEMORY_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_MEMORY_TNT_TIME ON HUB_METRIC_MEMORY_LOG (tenantId, collectTime);
