-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_SERVICE_NAMESPACE (
  namespaceId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  instanceName VARCHAR(100) NOT NULL,
  environment VARCHAR(32) NOT NULL,
  namespaceName VARCHAR(100) NOT NULL,
  namespaceDescription VARCHAR(500) DEFAULT NULL,
  serviceQuotaLimit INT DEFAULT 200,
  configQuotaLimit INT DEFAULT 200,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  PRIMARY KEY (tenantId, namespaceId)
);
CREATE INDEX IF NOT EXISTS IDX_SVC_NS_NAME ON HUB_SERVICE_NAMESPACE (tenantId, namespaceName);
CREATE INDEX IF NOT EXISTS IDX_SVC_NS_INSTANCE ON HUB_SERVICE_NAMESPACE (tenantId, instanceName, environment);
CREATE INDEX IF NOT EXISTS IDX_SVC_NS_ENV ON HUB_SERVICE_NAMESPACE (environment);
CREATE INDEX IF NOT EXISTS IDX_SVC_NS_ACTIVE ON HUB_SERVICE_NAMESPACE (activeFlag);
