-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_ALERT_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  channelName VARCHAR(100) NOT NULL,
  channelType VARCHAR(50) NOT NULL,
  channelDesc VARCHAR(500) DEFAULT NULL,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  defaultFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  priorityLevel INT NOT NULL DEFAULT 10,
  defaultTemplateName VARCHAR(100) DEFAULT NULL,
  serverConfig TEXT DEFAULT NULL,
  sendConfig TEXT DEFAULT NULL,
  messageContentFormat VARCHAR(20) DEFAULT NULL,
  timeoutSeconds INT NOT NULL DEFAULT 30,
  retryCount INT NOT NULL DEFAULT 3,
  retryIntervalSecs INT NOT NULL DEFAULT 5,
  asyncSendFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  totalSentCount BIGINT NOT NULL DEFAULT 0,
  successCount BIGINT NOT NULL DEFAULT 0,
  failureCount BIGINT NOT NULL DEFAULT 0,
  lastSendTime TIMESTAMP DEFAULT NULL,
  lastSuccessTime TIMESTAMP DEFAULT NULL,
  lastFailureTime TIMESTAMP DEFAULT NULL,
  lastErrorMessage VARCHAR(1000) DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, channelName)
);
CREATE INDEX IF NOT EXISTS IDX_ALERT_CONFIG_TENANT ON HUB_ALERT_CONFIG (tenantId);
CREATE INDEX IF NOT EXISTS IDX_ALERT_CONFIG_TYPE ON HUB_ALERT_CONFIG (channelType);
CREATE INDEX IF NOT EXISTS IDX_ALERT_CONFIG_ACTIVE ON HUB_ALERT_CONFIG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_ALERT_CONFIG_DEFAULT ON HUB_ALERT_CONFIG (defaultFlag);
CREATE INDEX IF NOT EXISTS IDX_ALERT_CONFIG_PRIORITY ON HUB_ALERT_CONFIG (priorityLevel);
CREATE INDEX IF NOT EXISTS IDX_ALERT_CONFIG_TEMPLATE ON HUB_ALERT_CONFIG (defaultTemplateName);
