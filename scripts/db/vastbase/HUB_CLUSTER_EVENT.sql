-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_CLUSTER_EVENT (
  eventId VARCHAR(64) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  sourceNodeId VARCHAR(100) NOT NULL,
  sourceNodeIp VARCHAR(100) DEFAULT NULL,
  eventType VARCHAR(50) NOT NULL,
  eventAction VARCHAR(50) NOT NULL,
  eventPayload TEXT DEFAULT NULL,
  eventTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expireTime TIMESTAMP DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(64) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(64) NOT NULL,
  oprSeqFlag VARCHAR(64) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText TEXT DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, eventId)
);
CREATE INDEX IF NOT EXISTS IDX_CLS_EVT_QUERY ON HUB_CLUSTER_EVENT (tenantId, activeFlag, eventTime, eventId);
CREATE INDEX IF NOT EXISTS IDX_CLS_EVT_SOURCE ON HUB_CLUSTER_EVENT (sourceNodeId);
CREATE INDEX IF NOT EXISTS IDX_CLS_EVT_TYPE ON HUB_CLUSTER_EVENT (eventType, eventTime);
CREATE INDEX IF NOT EXISTS IDX_CLS_EVT_EXPIRE ON HUB_CLUSTER_EVENT (expireTime);
CREATE INDEX IF NOT EXISTS IDX_CLS_EVT_CLEANUP ON HUB_CLUSTER_EVENT (tenantId, eventTime);
