-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_TEMP_LOG (
  metricTemperatureLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  sensorName VARCHAR(100) NOT NULL,
  temperatureValue DECIMAL(6,2) NOT NULL DEFAULT 0.00,
  highThreshold DECIMAL(6,2) DEFAULT NULL,
  criticalThreshold DECIMAL(6,2) DEFAULT NULL,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricTemperatureLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_SERVER ON HUB_METRIC_TEMP_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_TIME ON HUB_METRIC_TEMP_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_SENSOR ON HUB_METRIC_TEMP_LOG (sensorName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_ACTIVE ON HUB_METRIC_TEMP_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_SRV_TIME ON HUB_METRIC_TEMP_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_SRV_SENSOR ON HUB_METRIC_TEMP_LOG (metricServerId, sensorName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_TEMP_TNT_TIME ON HUB_METRIC_TEMP_LOG (tenantId, collectTime);
