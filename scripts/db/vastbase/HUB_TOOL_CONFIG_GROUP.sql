-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TOOL_CONFIG_GROUP (
  configGroupId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  groupName VARCHAR(100) NOT NULL,
  groupDescription VARCHAR(500) DEFAULT NULL,
  parentGroupId VARCHAR(32) DEFAULT NULL,
  groupLevel INT DEFAULT 1,
  groupPath VARCHAR(500) DEFAULT NULL,
  groupType VARCHAR(50) DEFAULT NULL,
  sortOrder INT DEFAULT 100,
  groupIcon VARCHAR(100) DEFAULT NULL,
  groupColor VARCHAR(20) DEFAULT NULL,
  accessLevel VARCHAR(20) DEFAULT 'private',
  allowedUsers TEXT DEFAULT NULL,
  allowedRoles TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, configGroupId)
);
CREATE INDEX IF NOT EXISTS IDX_TOOL_GROUP_NAME ON HUB_TOOL_CONFIG_GROUP (groupName);
CREATE INDEX IF NOT EXISTS IDX_TOOL_GROUP_PARENT ON HUB_TOOL_CONFIG_GROUP (parentGroupId);
CREATE INDEX IF NOT EXISTS IDX_TOOL_GROUP_TYPE ON HUB_TOOL_CONFIG_GROUP (groupType);
CREATE INDEX IF NOT EXISTS IDX_TOOL_GROUP_SORT ON HUB_TOOL_CONFIG_GROUP (sortOrder);
CREATE INDEX IF NOT EXISTS IDX_TOOL_GROUP_ACTIVE ON HUB_TOOL_CONFIG_GROUP (activeFlag);
