-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_THR_STATE (
  threadStateId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmThreadId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  newThreadCount INT NOT NULL DEFAULT 0,
  runnableThreadCount INT NOT NULL DEFAULT 0,
  blockedThreadCount INT NOT NULL DEFAULT 0,
  waitingThreadCount INT NOT NULL DEFAULT 0,
  timedWaitingThreadCount INT NOT NULL DEFAULT 0,
  terminatedThreadCount INT NOT NULL DEFAULT 0,
  totalThreadCount INT NOT NULL DEFAULT 0,
  activeThreadRatioPercent DECIMAL(5,2) DEFAULT 0.00,
  blockedThreadRatioPercent DECIMAL(5,2) DEFAULT 0.00,
  waitingThreadRatioPercent DECIMAL(5,2) DEFAULT 0.00,
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  healthGrade VARCHAR(20) DEFAULT NULL,
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, threadStateId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THRST_THR ON HUB_MONITOR_JVM_THR_STATE (jvmThreadId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THRST_RES ON HUB_MONITOR_JVM_THR_STATE (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THRST_TIME ON HUB_MONITOR_JVM_THR_STATE (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THRST_BLOCK ON HUB_MONITOR_JVM_THR_STATE (blockedThreadCount);
