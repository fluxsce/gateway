-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_ROUTE_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  routeConfigId VARCHAR(32) NOT NULL,
  gatewayInstanceId VARCHAR(32) NOT NULL,
  routeName VARCHAR(100) NOT NULL,
  routePath VARCHAR(200) NOT NULL,
  allowedMethods VARCHAR(200) DEFAULT NULL,
  allowedHosts VARCHAR(500) DEFAULT NULL,
  matchType INT NOT NULL DEFAULT 1,
  routePriority INT NOT NULL DEFAULT 100,
  stripPathPrefix VARCHAR(1) NOT NULL DEFAULT 'N',
  rewritePath VARCHAR(200) DEFAULT NULL,
  enableWebsocket VARCHAR(1) NOT NULL DEFAULT 'N',
  timeoutMs INT NOT NULL DEFAULT 30000,
  retryCount INT NOT NULL DEFAULT 0,
  retryIntervalMs INT NOT NULL DEFAULT 1000,
  serviceDefinitionId VARCHAR(32) DEFAULT NULL,
  logConfigId VARCHAR(32) DEFAULT NULL,
  routeMetadata TEXT DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, routeConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTE_INST ON HUB_GW_ROUTE_CONFIG (gatewayInstanceId);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTE_SERVICE ON HUB_GW_ROUTE_CONFIG (serviceDefinitionId);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTE_LOG ON HUB_GW_ROUTE_CONFIG (logConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTE_PRIORITY ON HUB_GW_ROUTE_CONFIG (routePriority);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTE_PATH ON HUB_GW_ROUTE_CONFIG (routePath);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTE_ACTIVE ON HUB_GW_ROUTE_CONFIG (activeFlag);

