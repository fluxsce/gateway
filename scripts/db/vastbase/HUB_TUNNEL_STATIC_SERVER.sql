-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TUNNEL_STATIC_SERVER (
  tunnelStaticServerId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  serverName VARCHAR(100) NOT NULL,
  serverDescription VARCHAR(500) DEFAULT NULL,
  listenAddress VARCHAR(50) NOT NULL DEFAULT '0.0.0.0',
  listenPort INT NOT NULL,
  serverType VARCHAR(20) NOT NULL DEFAULT 'tcp',
  maxConnections INT NOT NULL DEFAULT 1000,
  connectionTimeout INT NOT NULL DEFAULT 60,
  readTimeout INT NOT NULL DEFAULT 30,
  writeTimeout INT NOT NULL DEFAULT 30,
  tlsEnable VARCHAR(1) NOT NULL DEFAULT 'N',
  tlsCertFile VARCHAR(255) DEFAULT NULL,
  tlsKeyFile VARCHAR(255) DEFAULT NULL,
  tlsCaFile VARCHAR(255) DEFAULT NULL,
  logLevel VARCHAR(10) NOT NULL DEFAULT 'info',
  logFile VARCHAR(255) DEFAULT NULL,
  serverStatus VARCHAR(20) NOT NULL DEFAULT 'stopped',
  startTime TIMESTAMP DEFAULT NULL,
  stopTime TIMESTAMP DEFAULT NULL,
  currentConnectionCount INT DEFAULT 0,
  totalConnectionCount BIGINT DEFAULT 0,
  totalBytesReceived BIGINT DEFAULT 0,
  totalBytesSent BIGINT DEFAULT 0,
  healthCheckType VARCHAR(20) DEFAULT 'tcp',
  healthCheckUrl VARCHAR(255) DEFAULT NULL,
  healthCheckInterval INT DEFAULT 30,
  healthCheckTimeout INT DEFAULT 5,
  healthCheckMaxFailures INT DEFAULT 3,
  loadBalanceType VARCHAR(20) DEFAULT 'roundrobin',
  serverConfig TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  CONSTRAINT PK_TUNNEL_STATIC_SVR PRIMARY KEY (tunnelStaticServerId),
  CONSTRAINT IDX_TUNNEL_STATIC_SVR_NAME UNIQUE (serverName),
  CONSTRAINT IDX_TUNNEL_STATIC_SVR_PORT UNIQUE (listenAddress, listenPort, serverType)
);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_SVR_TENANT ON HUB_TUNNEL_STATIC_SERVER (tenantId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_SVR_STATUS ON HUB_TUNNEL_STATIC_SERVER (serverStatus);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_STATIC_SVR_TYPE ON HUB_TUNNEL_STATIC_SERVER (serverType);
