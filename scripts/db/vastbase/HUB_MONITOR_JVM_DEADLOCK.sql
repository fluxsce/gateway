-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_DEADLOCK (
  deadlockId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmThreadId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  hasDeadlockFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  deadlockThreadCount INT NOT NULL DEFAULT 0,
  deadlockThreadIds TEXT DEFAULT NULL,
  deadlockThreadNames TEXT DEFAULT NULL,
  severityLevel VARCHAR(20) DEFAULT NULL,
  severityDescription VARCHAR(200) DEFAULT NULL,
  affectedThreadGroups INT DEFAULT 0,
  detectionTime TIMESTAMP DEFAULT NULL,
  deadlockDurationMs BIGINT DEFAULT 0,
  collectionTime TIMESTAMP NOT NULL,
  descriptionText VARCHAR(500) DEFAULT NULL,
  recommendedAction VARCHAR(500) DEFAULT NULL,
  alertLevel VARCHAR(20) DEFAULT NULL,
  requiresActionFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, deadlockId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_DL_THR ON HUB_MONITOR_JVM_DEADLOCK (jvmThreadId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_DL_RES ON HUB_MONITOR_JVM_DEADLOCK (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_DL_TIME ON HUB_MONITOR_JVM_DEADLOCK (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_DL_FLAG ON HUB_MONITOR_JVM_DEADLOCK (hasDeadlockFlag);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_DL_SEV ON HUB_MONITOR_JVM_DEADLOCK (severityLevel);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_DL_ALERT ON HUB_MONITOR_JVM_DEADLOCK (alertLevel);
