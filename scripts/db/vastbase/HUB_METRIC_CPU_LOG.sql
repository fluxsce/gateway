-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_CPU_LOG (
  metricCpuLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  usagePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  userPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  systemPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  idlePercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  ioWaitPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  irqPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  softIrqPercent DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  coreCount INT NOT NULL DEFAULT 0,
  logicalCount INT NOT NULL DEFAULT 0,
  loadAvg1 DECIMAL(8,2) NOT NULL DEFAULT 0.00,
  loadAvg5 DECIMAL(8,2) NOT NULL DEFAULT 0.00,
  loadAvg15 DECIMAL(8,2) NOT NULL DEFAULT 0.00,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricCpuLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_CPU_SERVER ON HUB_METRIC_CPU_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_CPU_TIME ON HUB_METRIC_CPU_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_CPU_USAGE ON HUB_METRIC_CPU_LOG (usagePercent);
CREATE INDEX IF NOT EXISTS IDX_METRIC_CPU_ACTIVE ON HUB_METRIC_CPU_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_CPU_SRV_TIME ON HUB_METRIC_CPU_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_CPU_TNT_TIME ON HUB_METRIC_CPU_LOG (tenantId, collectTime);
