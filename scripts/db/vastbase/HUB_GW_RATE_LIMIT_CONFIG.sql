-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_RATE_LIMIT_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  rateLimitConfigId VARCHAR(32) NOT NULL,
  gatewayInstanceId VARCHAR(32) DEFAULT NULL,
  routeConfigId VARCHAR(32) DEFAULT NULL,
  limitName VARCHAR(100) NOT NULL,
  algorithm VARCHAR(50) NOT NULL DEFAULT 'token-bucket',
  keyStrategy VARCHAR(50) NOT NULL DEFAULT 'ip',
  limitRate INT NOT NULL,
  burstCapacity INT NOT NULL DEFAULT 0,
  timeWindowSeconds INT NOT NULL DEFAULT 1,
  rejectionStatusCode INT NOT NULL DEFAULT 429,
  rejectionMessage VARCHAR(200) DEFAULT '请求过于频繁，请稍后再试',
  configPriority INT NOT NULL DEFAULT 0,
  customConfig TEXT DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, rateLimitConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_RATE_INST ON HUB_GW_RATE_LIMIT_CONFIG (gatewayInstanceId);
CREATE INDEX IF NOT EXISTS IDX_GW_RATE_ROUTE ON HUB_GW_RATE_LIMIT_CONFIG (routeConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_RATE_STRATEGY ON HUB_GW_RATE_LIMIT_CONFIG (keyStrategy);
CREATE INDEX IF NOT EXISTS IDX_GW_RATE_ALGORITHM ON HUB_GW_RATE_LIMIT_CONFIG (algorithm);
CREATE INDEX IF NOT EXISTS IDX_GW_RATE_PRIORITY ON HUB_GW_RATE_LIMIT_CONFIG (configPriority);
CREATE INDEX IF NOT EXISTS IDX_GW_RATE_ACTIVE ON HUB_GW_RATE_LIMIT_CONFIG (activeFlag);
