-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_CIRCUIT_BREAKER_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  circuitBreakerConfigId VARCHAR(32) NOT NULL,
  routeConfigId VARCHAR(32) DEFAULT NULL,
  targetServiceId VARCHAR(32) DEFAULT NULL,
  breakerName VARCHAR(100) NOT NULL,
  keyStrategy VARCHAR(50) NOT NULL DEFAULT 'node',
  errorRatePercent INT NOT NULL DEFAULT 50,
  minimumRequests INT NOT NULL DEFAULT 10,
  halfOpenMaxRequests INT NOT NULL DEFAULT 3,
  slowCallThreshold INT NOT NULL DEFAULT 60000,
  slowCallRatePercent INT NOT NULL DEFAULT 50,
  openTimeoutSeconds INT NOT NULL DEFAULT 60,
  windowSizeSeconds INT NOT NULL DEFAULT 60,
  errorStatusCode INT NOT NULL DEFAULT 503,
  errorMessage VARCHAR(500) DEFAULT 'Service temporarily unavailable due to circuit breaker',
  storageType VARCHAR(50) NOT NULL DEFAULT 'memory',
  storageConfig TEXT DEFAULT NULL,
  configPriority INT NOT NULL DEFAULT 0,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, circuitBreakerConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_CB_ROUTE ON HUB_GW_CIRCUIT_BREAKER_CONFIG (routeConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_CB_SERVICE ON HUB_GW_CIRCUIT_BREAKER_CONFIG (targetServiceId);
CREATE INDEX IF NOT EXISTS IDX_GW_CB_STRATEGY ON HUB_GW_CIRCUIT_BREAKER_CONFIG (keyStrategy);
CREATE INDEX IF NOT EXISTS IDX_GW_CB_STORAGE ON HUB_GW_CIRCUIT_BREAKER_CONFIG (storageType);
CREATE INDEX IF NOT EXISTS IDX_GW_CB_PRIORITY ON HUB_GW_CIRCUIT_BREAKER_CONFIG (configPriority);
