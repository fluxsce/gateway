-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TUNNEL_SERVICE (
  tunnelServiceId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  tunnelClientId VARCHAR(32) NOT NULL,
  userId VARCHAR(32) NOT NULL,
  serviceName VARCHAR(100) NOT NULL,
  serviceDescription VARCHAR(500) DEFAULT NULL,
  serviceType VARCHAR(20) NOT NULL,
  localAddress VARCHAR(50) NOT NULL DEFAULT '127.0.0.1',
  localPort INT NOT NULL,
  remotePort INT DEFAULT NULL,
  customDomains TEXT DEFAULT NULL,
  subDomain VARCHAR(100) DEFAULT NULL,
  httpUser VARCHAR(50) DEFAULT NULL,
  httpPassword VARCHAR(100) DEFAULT NULL,
  hostHeaderRewrite VARCHAR(255) DEFAULT NULL,
  headers TEXT DEFAULT NULL,
  locations TEXT DEFAULT NULL,
  useEncryption VARCHAR(1) NOT NULL DEFAULT 'N',
  useCompression VARCHAR(1) NOT NULL DEFAULT 'Y',
  secretKey VARCHAR(100) DEFAULT NULL,
  bandwidthLimit VARCHAR(20) DEFAULT NULL,
  maxConnections INT DEFAULT 100,
  healthCheckType VARCHAR(20) DEFAULT NULL,
  healthCheckUrl VARCHAR(255) DEFAULT NULL,
  serviceStatus VARCHAR(20) NOT NULL DEFAULT 'active',
  registeredTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lastActiveTime TIMESTAMP DEFAULT NULL,
  connectionCount INT DEFAULT 0,
  totalConnections BIGINT DEFAULT 0,
  totalTraffic BIGINT DEFAULT 0,
  serviceConfig TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  CONSTRAINT PK_TUNNEL_SERVICE PRIMARY KEY (tunnelServiceId),
  CONSTRAINT IDX_TUNNEL_SVC_NAME UNIQUE (serviceName)
);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_TENANT ON HUB_TUNNEL_SERVICE (tenantId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_CLIENT ON HUB_TUNNEL_SERVICE (tunnelClientId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_USER ON HUB_TUNNEL_SERVICE (userId);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_TYPE ON HUB_TUNNEL_SERVICE (serviceType);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_STATUS ON HUB_TUNNEL_SERVICE (serviceStatus);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_PORT ON HUB_TUNNEL_SERVICE (remotePort);
CREATE INDEX IF NOT EXISTS IDX_TUNNEL_SVC_DOMAIN ON HUB_TUNNEL_SERVICE (subDomain);
