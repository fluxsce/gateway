-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_SERVICE_CONFIG_HISTORY (
  configHistoryId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  configDataId VARCHAR(100) NOT NULL,
  namespaceId VARCHAR(32) NOT NULL,
  groupName VARCHAR(64) NOT NULL,
  changeType VARCHAR(20) NOT NULL,
  oldContent TEXT DEFAULT NULL,
  newContent TEXT NOT NULL,
  oldVersion BIGINT DEFAULT NULL,
  newVersion BIGINT NOT NULL,
  oldMd5Value VARCHAR(32) DEFAULT NULL,
  newMd5Value VARCHAR(32) NOT NULL,
  changeReason VARCHAR(500) DEFAULT NULL,
  changedBy VARCHAR(32) NOT NULL,
  changedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  PRIMARY KEY (tenantId, configHistoryId)
);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_DATA_ID ON HUB_SERVICE_CONFIG_HISTORY (tenantId, configDataId);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_NS_ID ON HUB_SERVICE_CONFIG_HISTORY (tenantId, namespaceId);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_GROUP_NAME ON HUB_SERVICE_CONFIG_HISTORY (tenantId, namespaceId, groupName);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_TYPE ON HUB_SERVICE_CONFIG_HISTORY (changeType);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_TIME ON HUB_SERVICE_CONFIG_HISTORY (changedAt);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_BY ON HUB_SERVICE_CONFIG_HISTORY (changedBy);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_HIST_VERSION ON HUB_SERVICE_CONFIG_HISTORY (newVersion);
