-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_MONITOR_JVM_THREAD (
  jvmThreadId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  jvmResourceId VARCHAR(100) NOT NULL,
  currentThreadCount INT NOT NULL DEFAULT 0,
  daemonThreadCount INT NOT NULL DEFAULT 0,
  userThreadCount INT NOT NULL DEFAULT 0,
  peakThreadCount INT NOT NULL DEFAULT 0,
  totalStartedThreadCount BIGINT NOT NULL DEFAULT 0,
  threadGrowthRatePercent DECIMAL(5,2) DEFAULT 0.00,
  daemonThreadRatioPercent DECIMAL(5,2) DEFAULT 0.00,
  cpuTimeSupported VARCHAR(1) NOT NULL DEFAULT 'N',
  cpuTimeEnabled VARCHAR(1) NOT NULL DEFAULT 'N',
  memoryAllocSupported VARCHAR(1) NOT NULL DEFAULT 'N',
  memoryAllocEnabled VARCHAR(1) NOT NULL DEFAULT 'N',
  contentionSupported VARCHAR(1) NOT NULL DEFAULT 'N',
  contentionEnabled VARCHAR(1) NOT NULL DEFAULT 'N',
  healthyFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  healthGrade VARCHAR(20) DEFAULT NULL,
  requiresAttentionFlag VARCHAR(1) NOT NULL DEFAULT 'N',
  potentialIssuesJson TEXT DEFAULT NULL,
  collectionTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) DEFAULT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) DEFAULT NULL,
  oprSeqFlag VARCHAR(32) DEFAULT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, jvmThreadId)
);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THR_RES ON HUB_MONITOR_JVM_THREAD (jvmResourceId);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THR_TIME ON HUB_MONITOR_JVM_THREAD (collectionTime);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THR_HEALTH ON HUB_MONITOR_JVM_THREAD (healthyFlag, requiresAttentionFlag);
CREATE INDEX IF NOT EXISTS IDX_MONITOR_THR_COUNT ON HUB_MONITOR_JVM_THREAD (currentThreadCount);
