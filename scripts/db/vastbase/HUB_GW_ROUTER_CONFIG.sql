-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_ROUTER_CONFIG (
  tenantId VARCHAR(32) NOT NULL,
  routerConfigId VARCHAR(32) NOT NULL,
  gatewayInstanceId VARCHAR(32) NOT NULL,
  routerName VARCHAR(100) NOT NULL,
  routerDesc VARCHAR(200) DEFAULT NULL,
  defaultPriority INT NOT NULL DEFAULT 100,
  enableRouteCache VARCHAR(1) NOT NULL DEFAULT 'Y',
  routeCacheTtlSeconds INT NOT NULL DEFAULT 300,
  maxRoutes INT DEFAULT 1000,
  routeMatchTimeout INT DEFAULT 100,
  enableStrictMode VARCHAR(1) NOT NULL DEFAULT 'N',
  enableMetrics VARCHAR(1) NOT NULL DEFAULT 'Y',
  enableTracing VARCHAR(1) NOT NULL DEFAULT 'N',
  caseSensitive VARCHAR(1) NOT NULL DEFAULT 'Y',
  removeTrailingSlash VARCHAR(1) NOT NULL DEFAULT 'Y',
  enableGlobalFilters VARCHAR(1) NOT NULL DEFAULT 'Y',
  filterExecutionMode VARCHAR(20) NOT NULL DEFAULT 'SEQUENTIAL',
  maxFilterChainDepth INT DEFAULT 50,
  enableRoutePooling VARCHAR(1) NOT NULL DEFAULT 'N',
  routePoolSize INT DEFAULT 100,
  enableAsyncProcessing VARCHAR(1) NOT NULL DEFAULT 'N',
  enableFallback VARCHAR(1) NOT NULL DEFAULT 'Y',
  fallbackRoute VARCHAR(200) DEFAULT NULL,
  notFoundStatusCode INT NOT NULL DEFAULT 404,
  notFoundMessage VARCHAR(200) DEFAULT 'Route not found',
  routerMetadata TEXT DEFAULT NULL,
  customConfig TEXT DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, routerConfigId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTER_INST ON HUB_GW_ROUTER_CONFIG (gatewayInstanceId);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTER_NAME ON HUB_GW_ROUTER_CONFIG (routerName);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTER_ACTIVE ON HUB_GW_ROUTER_CONFIG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_GW_ROUTER_CACHE ON HUB_GW_ROUTER_CONFIG (enableRouteCache);
