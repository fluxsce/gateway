-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_METRIC_DISK_IO_LOG (
  metricDiskIoLogId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  metricServerId VARCHAR(32) NOT NULL,
  deviceName VARCHAR(100) NOT NULL,
  readCount BIGINT NOT NULL DEFAULT 0,
  writeCount BIGINT NOT NULL DEFAULT 0,
  readBytes BIGINT NOT NULL DEFAULT 0,
  writeBytes BIGINT NOT NULL DEFAULT 0,
  readTime BIGINT NOT NULL DEFAULT 0,
  writeTime BIGINT NOT NULL DEFAULT 0,
  ioInProgress BIGINT NOT NULL DEFAULT 0,
  ioTime BIGINT NOT NULL DEFAULT 0,
  readRate DECIMAL(20,2) NOT NULL DEFAULT 0.00,
  writeRate DECIMAL(20,2) NOT NULL DEFAULT 0.00,
  collectTime TIMESTAMP NOT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, metricDiskIoLogId)
);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_SERVER ON HUB_METRIC_DISK_IO_LOG (metricServerId);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_TIME ON HUB_METRIC_DISK_IO_LOG (collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_DEVICE ON HUB_METRIC_DISK_IO_LOG (deviceName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_ACTIVE ON HUB_METRIC_DISK_IO_LOG (activeFlag);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_SRV_TIME ON HUB_METRIC_DISK_IO_LOG (metricServerId, collectTime);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_SRV_DEV ON HUB_METRIC_DISK_IO_LOG (metricServerId, deviceName);
CREATE INDEX IF NOT EXISTS IDX_METRIC_DISK_IO_TNT_TIME ON HUB_METRIC_DISK_IO_LOG (tenantId, collectTime);
