-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_TIMER_SCHEDULER (
  schedulerId VARCHAR(32) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  schedulerName VARCHAR(100) NOT NULL,
  schedulerInstanceId VARCHAR(100) DEFAULT NULL,
  maxWorkers INT NOT NULL DEFAULT 5,
  queueSize INT NOT NULL DEFAULT 100,
  defaultTimeoutSeconds BIGINT NOT NULL DEFAULT 1800,
  defaultRetries INT NOT NULL DEFAULT 3,
  schedulerStatus INT NOT NULL DEFAULT 1,
  lastStartTime TIMESTAMP DEFAULT NULL,
  lastStopTime TIMESTAMP DEFAULT NULL,
  serverName VARCHAR(100) DEFAULT NULL,
  serverIp VARCHAR(50) DEFAULT NULL,
  serverPort INT DEFAULT NULL,
  totalTaskCount INT NOT NULL DEFAULT 0,
  runningTaskCount INT NOT NULL DEFAULT 0,
  lastHeartbeatTime TIMESTAMP DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, schedulerId)
);
CREATE INDEX IF NOT EXISTS IDX_TIMER_SCHED_NAME ON HUB_TIMER_SCHEDULER (schedulerName);
CREATE INDEX IF NOT EXISTS IDX_TIMER_SCHED_INST ON HUB_TIMER_SCHEDULER (schedulerInstanceId);
CREATE INDEX IF NOT EXISTS IDX_TIMER_SCHED_STATUS ON HUB_TIMER_SCHEDULER (schedulerStatus);
CREATE INDEX IF NOT EXISTS IDX_TIMER_SCHED_HEART ON HUB_TIMER_SCHEDULER (lastHeartbeatTime);
