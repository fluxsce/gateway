-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_ALERT_LOG (
  tenantId VARCHAR(32) NOT NULL,
  alertLogId VARCHAR(32) NOT NULL,
  alertLevel VARCHAR(20) NOT NULL DEFAULT 'INFO',
  alertType VARCHAR(100) DEFAULT NULL,
  alertTitle VARCHAR(500) NOT NULL,
  alertContent TEXT DEFAULT NULL,
  alertTimestamp TIMESTAMP NOT NULL,
  channelName VARCHAR(100) DEFAULT NULL,
  sendStatus VARCHAR(20) DEFAULT NULL,
  sendTime TIMESTAMP DEFAULT NULL,
  sendResult TEXT DEFAULT NULL,
  sendErrorMessage TEXT DEFAULT NULL,
  alertTags TEXT DEFAULT NULL,
  alertExtra TEXT DEFAULT NULL,
  tableData TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  reserved1 VARCHAR(500) DEFAULT NULL,
  reserved2 VARCHAR(500) DEFAULT NULL,
  reserved3 VARCHAR(500) DEFAULT NULL,
  reserved4 VARCHAR(500) DEFAULT NULL,
  reserved5 VARCHAR(500) DEFAULT NULL,
  reserved6 VARCHAR(500) DEFAULT NULL,
  reserved7 VARCHAR(500) DEFAULT NULL,
  reserved8 VARCHAR(500) DEFAULT NULL,
  reserved9 VARCHAR(500) DEFAULT NULL,
  reserved10 VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, alertLogId)
);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_TENANT ON HUB_ALERT_LOG (tenantId);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_LEVEL ON HUB_ALERT_LOG (alertLevel);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_TYPE ON HUB_ALERT_LOG (alertType);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_TIMESTAMP ON HUB_ALERT_LOG (alertTimestamp);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_CHANNEL ON HUB_ALERT_LOG (channelName);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_SEND_STATUS ON HUB_ALERT_LOG (sendStatus);
CREATE INDEX IF NOT EXISTS idx_ALERT_LOG_TIME_STATUS ON HUB_ALERT_LOG (alertTimestamp, sendStatus);
CREATE INDEX IF NOT EXISTS IDX_ALERT_LOG_CLEANUP ON HUB_ALERT_LOG (tenantId, alertTimestamp);
