-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_SERVICE_CONFIG_DATA (
  configDataId VARCHAR(100) NOT NULL,
  tenantId VARCHAR(32) NOT NULL,
  namespaceId VARCHAR(32) NOT NULL,
  groupName VARCHAR(64) NOT NULL DEFAULT 'DEFAULT_GROUP',
  configContent TEXT NOT NULL,
  contentType VARCHAR(50) DEFAULT 'text',
  configDescription VARCHAR(500) DEFAULT NULL,
  encrypted VARCHAR(1) DEFAULT 'N',
  version BIGINT NOT NULL DEFAULT 1,
  md5Value VARCHAR(32) DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  PRIMARY KEY (tenantId, namespaceId, groupName, configDataId)
);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_DATA_NS_ID ON HUB_SERVICE_CONFIG_DATA (tenantId, namespaceId);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_DATA_MD5 ON HUB_SERVICE_CONFIG_DATA (md5Value);
CREATE INDEX IF NOT EXISTS IDX_SVC_CFG_DATA_ACTIVE ON HUB_SERVICE_CONFIG_DATA (activeFlag);
