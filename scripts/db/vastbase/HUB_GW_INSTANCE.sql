-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_INSTANCE (
  tenantId VARCHAR(32) NOT NULL,
  gatewayInstanceId VARCHAR(32) NOT NULL,
  instanceName VARCHAR(100) NOT NULL,
  instanceDesc VARCHAR(200) DEFAULT NULL,
  bindAddress VARCHAR(100) DEFAULT '0.0.0.0',
  httpPort INT DEFAULT NULL,
  httpsPort INT DEFAULT NULL,
  tlsEnabled VARCHAR(1) NOT NULL DEFAULT 'N',
  certStorageType VARCHAR(20) NOT NULL DEFAULT 'FILE',
  certFilePath VARCHAR(255) DEFAULT NULL,
  keyFilePath VARCHAR(255) DEFAULT NULL,
  certContent TEXT DEFAULT NULL,
  keyContent TEXT DEFAULT NULL,
  certChainContent TEXT DEFAULT NULL,
  certPassword VARCHAR(255) DEFAULT NULL,
  maxConnections INT NOT NULL DEFAULT 10000,
  readTimeoutMs INT NOT NULL DEFAULT 30000,
  writeTimeoutMs INT NOT NULL DEFAULT 30000,
  idleTimeoutMs INT NOT NULL DEFAULT 60000,
  maxHeaderBytes INT NOT NULL DEFAULT 1048576,
  maxWorkers INT NOT NULL DEFAULT 1000,
  keepAliveEnabled VARCHAR(1) NOT NULL DEFAULT 'Y',
  tcpKeepAliveEnabled VARCHAR(1) NOT NULL DEFAULT 'Y',
  gracefulShutdownTimeoutMs INT NOT NULL DEFAULT 30000,
  enableHttp2 VARCHAR(1) NOT NULL DEFAULT 'Y',
  tlsVersion VARCHAR(10) DEFAULT '1.2',
  tlsCipherSuites VARCHAR(1000) DEFAULT NULL,
  disableGeneralOptionsHandler VARCHAR(1) NOT NULL DEFAULT 'N',
  logConfigId VARCHAR(32) DEFAULT NULL,
  healthStatus VARCHAR(1) NOT NULL DEFAULT 'Y',
  lastHeartbeatTime TIMESTAMP DEFAULT NULL,
  instanceMetadata TEXT DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, gatewayInstanceId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_INST_BIND_HTTP ON HUB_GW_INSTANCE (bindAddress, httpPort);
CREATE INDEX IF NOT EXISTS IDX_GW_INST_BIND_HTTPS ON HUB_GW_INSTANCE (bindAddress, httpsPort);
CREATE INDEX IF NOT EXISTS IDX_GW_INST_LOG ON HUB_GW_INSTANCE (logConfigId);
CREATE INDEX IF NOT EXISTS IDX_GW_INST_HEALTH ON HUB_GW_INSTANCE (healthStatus);
CREATE INDEX IF NOT EXISTS IDX_GW_INST_TLS ON HUB_GW_INSTANCE (tlsEnabled);
