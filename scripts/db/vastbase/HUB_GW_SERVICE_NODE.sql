-- Vastbase（PostgreSQL 兼容模式）。由 scripts/db/mysql 转换。
CREATE TABLE IF NOT EXISTS HUB_GW_SERVICE_NODE (
  tenantId VARCHAR(32) NOT NULL,
  serviceNodeId VARCHAR(32) NOT NULL,
  serviceDefinitionId VARCHAR(32) NOT NULL,
  nodeId VARCHAR(100) NOT NULL,
  nodeUrl VARCHAR(500) NOT NULL,
  nodeHost VARCHAR(100) NOT NULL,
  nodePort INT NOT NULL,
  nodeProtocol VARCHAR(10) NOT NULL DEFAULT 'HTTP',
  nodeWeight INT NOT NULL DEFAULT 100,
  healthStatus VARCHAR(1) NOT NULL DEFAULT 'Y',
  nodeMetadata TEXT DEFAULT NULL,
  nodeStatus INT NOT NULL DEFAULT 1,
  lastHealthCheckTime TIMESTAMP DEFAULT NULL,
  healthCheckResult TEXT DEFAULT NULL,
  reserved1 VARCHAR(100) DEFAULT NULL,
  reserved2 VARCHAR(100) DEFAULT NULL,
  reserved3 INT DEFAULT NULL,
  reserved4 INT DEFAULT NULL,
  reserved5 TIMESTAMP DEFAULT NULL,
  extProperty TEXT DEFAULT NULL,
  addTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  addWho VARCHAR(32) NOT NULL,
  editTime TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  editWho VARCHAR(32) NOT NULL,
  oprSeqFlag VARCHAR(32) NOT NULL,
  currentVersion INT NOT NULL DEFAULT 1,
  activeFlag VARCHAR(1) NOT NULL DEFAULT 'Y',
  noteText VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (tenantId, serviceNodeId)
);
CREATE INDEX IF NOT EXISTS IDX_GW_NODE_SERVICE ON HUB_GW_SERVICE_NODE (serviceDefinitionId);
CREATE INDEX IF NOT EXISTS IDX_GW_NODE_ENDPOINT ON HUB_GW_SERVICE_NODE (nodeHost, nodePort);
CREATE INDEX IF NOT EXISTS IDX_GW_NODE_HEALTH ON HUB_GW_SERVICE_NODE (healthStatus);
CREATE INDEX IF NOT EXISTS IDX_GW_NODE_STATUS ON HUB_GW_SERVICE_NODE (nodeStatus);
